// Builds the web part of the Android app (mobile/www) from gui/.
// The interface is the same; the desktop core (electron/core.cjs) runs inside the WebView with
// a tiny Node shim, and the app data lives in the WebView's private storage instead of a file.
// Run: node tools/build-mobile.cjs  → then: npx cap sync android && (cd mobile/android && gradlew assembleDebug)
const fs = require("node:fs");
const path = require("node:path");

const root = path.join(__dirname, "..");
const out = path.join(root, "mobile", "www");
const version = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8")).version;

fs.rmSync(out, { recursive: true, force: true });
fs.cpSync(path.join(root, "gui"), out, {
  recursive: true,
  filter: (source) => !/\.part\d+\.json$/.test(source) && !source.endsWith("salah-guide.mp3"),
});
fs.copyFileSync(path.join(root, "mobile", "mobile.css"), path.join(out, "mobile.css"));

const wrap = (file) => `function (module, exports, require, process) {\n${fs.readFileSync(path.join(root, file), "utf8")}\n}`;
const core = `// Generated by tools/build-mobile.cjs – the Life core for Android.
(function () {
  "use strict";
  // ---- minimal Node shim: sha256 (sync), random bytes, process.env ----
  function sha256(text) {
    const bytes = new TextEncoder().encode(String(text));
    const K = [0x428a2f98,0x71374491,0xb5c0fbcf,0xe9b5dba5,0x3956c25b,0x59f111f1,0x923f82a4,0xab1c5ed5,0xd807aa98,0x12835b01,0x243185be,0x550c7dc3,0x72be5d74,0x80deb1fe,0x9bdc06a7,0xc19bf174,0xe49b69c1,0xefbe4786,0x0fc19dc6,0x240ca1cc,0x2de92c6f,0x4a7484aa,0x5cb0a9dc,0x76f988da,0x983e5152,0xa831c66d,0xb00327c8,0xbf597fc7,0xc6e00bf3,0xd5a79147,0x06ca6351,0x14292967,0x27b70a85,0x2e1b2138,0x4d2c6dfc,0x53380d13,0x650a7354,0x766a0abb,0x81c2c92e,0x92722c85,0xa2bfe8a1,0xa81a664b,0xc24b8b70,0xc76c51a3,0xd192e819,0xd6990624,0xf40e3585,0x106aa070,0x19a4c116,0x1e376c08,0x2748774c,0x34b0bcb5,0x391c0cb3,0x4ed8aa4a,0x5b9cca4f,0x682e6ff3,0x748f82ee,0x78a5636f,0x84c87814,0x8cc70208,0x90befffa,0xa4506ceb,0xbef9a3f7,0xc67178f2];
    const H = [0x6a09e667,0xbb67ae85,0x3c6ef372,0xa54ff53a,0x510e527f,0x9b05688c,0x1f83d9ab,0x5be0cd19];
    const length = bytes.length;
    const padded = new Uint8Array(((length + 9 + 63) >> 6) << 6);
    padded.set(bytes);
    padded[length] = 0x80;
    const view = new DataView(padded.buffer);
    view.setUint32(padded.length - 4, length * 8);
    view.setUint32(padded.length - 8, Math.floor(length / 0x20000000));
    const w = new Uint32Array(64);
    const rot = (x, n) => (x >>> n) | (x << (32 - n));
    for (let offset = 0; offset < padded.length; offset += 64) {
      for (let i = 0; i < 16; i++) w[i] = view.getUint32(offset + i * 4);
      for (let i = 16; i < 64; i++) {
        const s0 = rot(w[i - 15], 7) ^ rot(w[i - 15], 18) ^ (w[i - 15] >>> 3);
        const s1 = rot(w[i - 2], 17) ^ rot(w[i - 2], 19) ^ (w[i - 2] >>> 10);
        w[i] = (w[i - 16] + s0 + w[i - 7] + s1) >>> 0;
      }
      let [a, b, c, d, e, f, g, h] = H;
      for (let i = 0; i < 64; i++) {
        const t1 = (h + (rot(e, 6) ^ rot(e, 11) ^ rot(e, 25)) + ((e & f) ^ (~e & g)) + K[i] + w[i]) >>> 0;
        const t2 = ((rot(a, 2) ^ rot(a, 13) ^ rot(a, 22)) + ((a & b) ^ (a & c) ^ (b & c))) >>> 0;
        h = g; g = f; f = e; e = (d + t1) >>> 0; d = c; c = b; b = a; a = (t1 + t2) >>> 0;
      }
      [a, b, c, d, e, f, g, h].forEach((value, i) => { H[i] = (H[i] + value) >>> 0; });
    }
    return H.map((value) => value.toString(16).padStart(8, "0")).join("");
  }
  const nodeCrypto = {
    createHash: () => { let text = ""; const hash = { update: (part) => { text += part; return hash; }, digest: () => sha256(text) }; return hash; },
    randomBytes: (n) => { const hex = [...crypto.getRandomValues(new Uint8Array(n))].map((b) => b.toString(16).padStart(2, "0")).join(""); return { toString: () => hex }; },
    randomUUID: () => crypto.randomUUID(),
  };
  const process = { env: {} };
  const requireShim = (name) => (name === "node:crypto" ? nodeCrypto : {});
  const load = (factory) => { const module = { exports: {} }; factory(module, module.exports, requireShim, process); return module.exports; };

  const storeLib = load(${wrap("electron/store.cjs")});
  const coreLib = load(${wrap("electron/core.cjs")});

  // ---- data: the WebView's private storage on the phone ----
  const KEY = "life:data";
  let saved = {};
  try { saved = JSON.parse(localStorage.getItem(KEY) || "{}"); } catch { saved = {}; }
  const store = new storeLib.MemoryStore(saved);
  store.save = () => { try { localStorage.setItem(KEY, JSON.stringify(store.data)); } catch { /* storage full */ } };

  const listeners = new Set();
  const host = {
    emit: (type, payload = {}) => listeners.forEach((listener) => listener({ type, payload })),
    seal: (text) => text, // the app's storage is private to Life on Android
    unseal: (text) => text,
    openExternal: (url) => { window.open(url, "_blank"); },
    monitorAvailable: () => false,
    getAutostart: () => false,
    setAutostart: () => {},
    appState: () => ({ platform: "android" }),
    usage: () => ({ sessionMinutes: 0, todayMinutes: 0, lastNightMinutes: 0, daily: {} }),
    quitAction: () => ({}),
    showWindow: () => {},
    version: ${JSON.stringify(version)},
  };
  const core = coreLib.createCore({ store, host });
  core.ensureIdentity?.();
  window.resoDesktop = {
    platform: "android",
    invoke: async (route, { method = "GET", body } = {}) => core.handle(method, route, body),
    onEvent: (callback) => { listeners.add(callback); return () => listeners.delete(callback); },
  };
  const cloud = () => { try { core.scheduleCloud(); } catch { /* offline */ } };
  setTimeout(cloud, 5000);
  setInterval(cloud, 10 * 60000);
})();
`;
fs.writeFileSync(path.join(out, "mobile-core.js"), core);

// index.html: load the core first, the phone layout last; the core talks to the server and
// scripture APIs itself, so the connect-src opens up to https (CapacitorHttp sends them natively)
for (const page of ["index.html", "feedback.html"]) {
  const file = path.join(out, page);
  let html = fs.readFileSync(file, "utf8");
  html = html.replace(/connect-src 'self'/, "connect-src 'self' https:");
  html = html.replace(/<script type="module"/, '<script src="mobile-core.js"></script>\n    <script type="module"');
  html = html.replace("</head>", '  <link rel="stylesheet" href="mobile.css">\n  </head>');
  fs.writeFileSync(file, html);
}
console.log(`mobile/www ready (Life ${version})`);
