// Computes word timings for the prayer recordings (gui/faith/salah-text.js → gui/faith/salah-timing.js).
// Run: npx electron tools/align-clips.cjs
// Method: loudness curve (10 ms frames) → spoken parts → words placed along the spoken time by their
// letter count → each boundary moved to the quietest moment nearby. Re-run when recordings change.
const { app, BrowserWindow } = require("electron");
const fs = require("node:fs");
const path = require("node:path");
const { pathToFileURL } = require("node:url");

app.disableHardwareAcceleration();
const root = path.join(__dirname, "..");

async function analyse(win, url, end) {
  return win.webContents.executeJavaScript(`(async () => {
    const buffer = await (await fetch(${JSON.stringify(url)})).arrayBuffer();
    const audio = await new OfflineAudioContext(1, 44100, 44100).decodeAudioData(buffer);
    const data = audio.getChannelData(0);
    const frame = Math.floor(audio.sampleRate * 0.01);
    const limit = Math.min(data.length, Math.floor((${end || 0} || audio.duration) * audio.sampleRate));
    const env = [];
    for (let i = 0; i < limit; i += frame) { let sum = 0; for (let j = i; j < Math.min(i + frame, limit); j++) sum += data[j] * data[j]; env.push(Math.sqrt(sum / frame)); }
    return { env, duration: audio.duration };
  })()`);
}

const letters = (word) => word.replace(/[ً-ْٰـ]/g, "").length || 1; // without vowel marks

function align(env, words) {
  const smooth = env.map((_, i) => (env[i - 2] || 0) * 0.1 + (env[i - 1] || 0) * 0.2 + env[i] * 0.4 + (env[i + 1] || 0) * 0.2 + (env[i + 2] || 0) * 0.1);
  const max = Math.max(...smooth);
  const voiced = smooth.map((value) => value > max * 0.07);
  // close tiny gaps (< 120 ms) and drop tiny blips (< 60 ms)
  for (let i = 0; i < voiced.length; i++) if (!voiced[i]) { let j = i; while (j < voiced.length && !voiced[j]) j++; if (j - i < 12 && i > 0 && j < voiced.length) for (let k = i; k < j; k++) voiced[k] = true; i = j; }
  const frames = [];
  voiced.forEach((on, i) => on && frames.push(i));
  if (!frames.length) return words.map(() => [0, 0]);
  const weights = words.map(letters);
  const total = weights.reduce((a, b) => a + b, 0);
  const bounds = [frames[0]];
  let acc = 0;
  for (let i = 0; i < words.length - 1; i++) {
    acc += weights[i];
    let at = frames[Math.min(frames.length - 1, Math.round((acc / total) * (frames.length - 1)))];
    let best = at;
    for (let k = Math.max(0, at - 12); k <= Math.min(smooth.length - 1, at + 12); k++) if (smooth[k] < smooth[best]) best = k; // quietest moment nearby
    bounds.push(Math.max(best, bounds.at(-1) + 5));
  }
  bounds.push(frames.at(-1) + 1);
  return words.map((_, i) => [+(bounds[i] / 100).toFixed(2), +(bounds[i + 1] / 100).toFixed(2)]);
}

app.whenReady().then(async () => {
  const { FORMULAS } = await import(pathToFileURL(path.join(root, "gui/faith/salah-text.js")).href);
  const win = new BrowserWindow({ show: false });
  await win.loadURL("data:text/html,<p>align</p>");
  const timing = {};
  for (const [key, formula] of Object.entries(FORMULAS)) {
    timing[key] = [];
    for (const clip of formula.clips) {
      const words = formula.words.slice(clip.words[0], clip.words[1] + 1).map(([arabic]) => arabic);
      const { env } = await analyse(win, clip.url, clip.end);
      timing[key].push(align(env, words));
      console.log(key, clip.url.split("/").pop(), JSON.stringify(timing[key].at(-1)));
    }
  }
  const out = `// Generated by tools/align-clips.cjs – word timings (seconds) per formula and recording.\nexport const TIMING = ${JSON.stringify(timing)};\n`;
  fs.writeFileSync(path.join(root, "gui/faith/salah-timing.js"), out);
  app.quit();
});
